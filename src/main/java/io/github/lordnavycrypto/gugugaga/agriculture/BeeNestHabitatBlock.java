package io.github.lordnavycrypto.gugugaga.agriculture;

import net.minecraft.core.BlockPos;
import net.minecraft.core.registries.BuiltInRegistries;
import net.minecraft.network.chat.Component;
import net.minecraft.server.level.ServerLevel;
import net.minecraft.tags.BlockTags;
import net.minecraft.util.RandomSource;
import net.minecraft.world.InteractionResult;
import net.minecraft.world.entity.animal.Bee;
import net.minecraft.world.entity.player.Player;
import net.minecraft.world.level.Level;
import net.minecraft.world.level.LevelReader;
import net.minecraft.world.level.block.Block;
import net.minecraft.world.level.block.Blocks;
import net.minecraft.world.level.block.state.BlockBehaviour;
import net.minecraft.world.level.block.state.BlockState;
import net.minecraft.world.level.block.state.StateDefinition;
import net.minecraft.world.level.block.state.properties.IntegerProperty;
import net.minecraft.world.phys.AABB;
import net.minecraft.world.phys.BlockHitResult;

/**
 * A resource-efficient nest-site prototype for wild pollinator species. Its stage represents
 * habitat activity detected near a matching bee and food plants, not a physically occupied
 * colony or a real brood lifecycle. No honey or cocoons are generated by these blocks.
 */
public final class BeeNestHabitatBlock extends Block {
    public static final IntegerProperty ACTIVITY = IntegerProperty.create("activity", 0, 3);

    private final String beeSpecies;
    private final boolean groundNesting;

    public BeeNestHabitatBlock(String beeSpecies, boolean groundNesting,
                               BlockBehaviour.Properties properties) {
        super(properties.randomTicks());
        this.beeSpecies = beeSpecies;
        this.groundNesting = groundNesting;
        registerDefaultState(defaultBlockState().setValue(ACTIVITY, 0));
    }

    @Override
    protected void createBlockStateDefinition(StateDefinition.Builder<Block, BlockState> builder) {
        builder.add(ACTIVITY);
    }

    @Override
    public boolean canSurvive(BlockState state, LevelReader level, BlockPos pos) {
        if (!groundNesting) return super.canSurvive(state, level, pos);
        BlockState below = level.getBlockState(pos.below());
        return below.is(Blocks.DIRT) || below.is(Blocks.GRASS_BLOCK)
                || below.is(Blocks.COARSE_DIRT) || below.is(Blocks.ROOTED_DIRT)
                || below.is(Blocks.PODZOL) || below.is(Blocks.MYCELIUM)
                || below.is(Blocks.SAND) || below.is(Blocks.RED_SAND);
    }

    @Override
    public void randomTick(BlockState state, ServerLevel level, BlockPos pos, RandomSource random) {
        if (state.getValue(ACTIVITY) >= 3 || random.nextInt(4) != 0) return;
        if (!hasMatchingBee(level, pos) || !hasForage(level, pos)) return;
        level.setBlock(pos, state.setValue(ACTIVITY, state.getValue(ACTIVITY) + 1), 3);
    }

    private boolean hasMatchingBee(ServerLevel level, BlockPos pos) {
        for (Bee bee : level.getEntitiesOfClass(Bee.class, new AABB(pos).inflate(8.0D), Bee::isAlive)) {
            var key = BuiltInRegistries.ENTITY_TYPE.getKey(bee.getType());
            if (key != null && key.getNamespace().equals("gugugaga")
                    && key.getPath().equals(beeSpecies)) return true;
        }
        return false;
    }

    private boolean hasForage(ServerLevel level, BlockPos pos) {
        for (BlockPos p : BlockPos.betweenClosed(pos.offset(-4, -1, -4), pos.offset(4, 2, 4))) {
            if (!level.hasChunkAt(p)) continue;
            BlockState nearby = level.getBlockState(p);
            if (!beeSpecies.equals("squash_bee") && nearby.is(BlockTags.FLOWERS)) return true;
            if (nearby.getBlock() instanceof AgricultureCropBlock crop
                    && nearby.getValue(AgricultureCropBlock.AGE) >= 4) {
                String id = BuiltInRegistries.BLOCK.getKey(crop).getPath();
                if (beeSpecies.equals("squash_bee")) {
                    if (id.equals("cucumber_crop") || id.equals("zucchini_crop")) return true;
                } else if (crop != null && (id.equals("strawberry_crop")
                        || id.equals("blueberry_crop") || id.equals("raspberry_crop")
                        || id.equals("cranberry_crop") || id.equals("sunflower_seed_crop")
                        || id.equals("buckwheat_crop") || id.equals("cucumber_crop")
                        || id.equals("zucchini_crop"))) {
                    return true;
                }
            }
        }
        return false;
    }

    @Override
    public InteractionResult useWithoutItem(BlockState state, Level level, BlockPos pos,
                                            Player player, BlockHitResult hit) {
        if (level.isClientSide) return InteractionResult.SUCCESS;
        player.displayClientMessage(Component.translatable(
                "message.gugugaga.bee_habitat_activity", state.getValue(ACTIVITY), 3), true);
        return InteractionResult.CONSUME;
    }
}
