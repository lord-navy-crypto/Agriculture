package io.github.lordnavycrypto.gugugaga.agriculture;

import net.minecraft.core.BlockPos;
import net.minecraft.resources.ResourceLocation;
import net.minecraft.world.entity.Entity;
import net.minecraft.world.entity.EntityType;
import net.minecraft.core.Direction;
import net.minecraft.core.registries.BuiltInRegistries;
import net.minecraft.network.chat.Component;
import net.minecraft.server.level.ServerLevel;
import net.minecraft.tags.BlockTags;
import net.minecraft.util.RandomSource;
import net.minecraft.world.InteractionResult;
import net.minecraft.world.entity.animal.Bee;
import net.minecraft.world.entity.player.Player;
import net.minecraft.world.level.Level;
import net.minecraft.world.level.BlockGetter;
import net.minecraft.world.phys.shapes.CollisionContext;
import net.minecraft.world.phys.shapes.VoxelShape;
import net.minecraft.world.level.LevelReader;
import net.minecraft.world.level.LevelAccessor;
import net.minecraft.world.level.block.Block;
import net.minecraft.world.level.block.Blocks;
import net.minecraft.world.level.block.state.BlockBehaviour;
import net.minecraft.world.level.block.state.BlockState;
import net.minecraft.world.level.block.state.StateDefinition;
import net.minecraft.world.level.block.state.properties.IntegerProperty;
import net.minecraft.world.phys.AABB;
import java.util.Set;
import net.minecraft.world.phys.BlockHitResult;

/**
 * A resource-efficient nest-site prototype for wild pollinator species. Its stage represents
 * habitat activity detected near a matching bee and food plants, not a physically occupied
 * colony or a real brood lifecycle. No honey or cocoons are generated by these blocks.
 */
public final class BeeNestHabitatBlock extends Block {
    public static final IntegerProperty ACTIVITY = IntegerProperty.create("activity", 0, 3);
    // Selection and collision outlines match each nest's actual rendered silhouette,
    // rather than leaving invisible full-cube walls around a shallow soil burrow.
    private static final VoxelShape BUMBLE_MOUND = Block.box(2, 0, 2, 14, 9, 14);
    private static final VoxelShape MASON_HOTEL = Block.box(1, 0, 2, 15, 16, 15);
    private static final VoxelShape SQUASH_BURROW = Block.box(0, 0, 0, 16, 3, 16);
    private static final VoxelShape LEAFCUTTER_TUBES = Block.box(1, 0, 2, 15, 15, 14);

    private static final Set<String> SQUASH_FORAGE_CROPS =
            Set.of("zucchini_crop", "pumpkin_crop");
    private static final Set<String> BUMBLEBEE_SOLANACEOUS_CROPS =
            Set.of("tomato_crop", "eggplant_crop");
    private static final Set<String> GENERAL_FORAGE_CROPS = Set.of(
            "strawberry_crop", "blueberry_crop", "raspberry_crop", "cranberry_crop",
            "sunflower_seed_crop", "buckwheat_crop", "cucumber_crop", "zucchini_crop",
            "lavender_crop", "clover_crop", "canola_crop", "mustard_crop", "basil_crop",
            "mint_crop", "asparagus_crop", "pumpkin_crop", "pineapple_crop",
            "blackberry_crop", "blackcurrant_crop", "amaranth_crop", "chives_crop",
            "sweet_corn_crop");


    private final String beeSpecies;
    private final boolean groundNesting;

    public BeeNestHabitatBlock(String beeSpecies, boolean groundNesting,
                               BlockBehaviour.Properties properties) {
        super(properties.randomTicks());
        this.beeSpecies = beeSpecies;
        this.groundNesting = groundNesting;
        registerDefaultState(defaultBlockState().setValue(ACTIVITY, 0));
    }

    @Override
    protected void createBlockStateDefinition(StateDefinition.Builder<Block, BlockState> builder) {
        builder.add(ACTIVITY);
    }

    @Override
    protected VoxelShape getShape(BlockState state, BlockGetter level, BlockPos pos,
                                  CollisionContext context) {
        return switch (beeSpecies) {
            case "bumblebee" -> BUMBLE_MOUND;
            case "mason_bee" -> MASON_HOTEL;
            case "squash_bee" -> SQUASH_BURROW;
            case "leafcutter_bee" -> LEAFCUTTER_TUBES;
            default -> BUMBLE_MOUND;
        };
    }

    @Override
    protected VoxelShape getCollisionShape(BlockState state, BlockGetter level, BlockPos pos,
                                           CollisionContext context) {
        return getShape(state, level, pos, context);
    }

    @Override
    public boolean canSurvive(BlockState state, LevelReader level, BlockPos pos) {
        // Crafted above-ground bee hotels and sheltered cavities need a solid
        // support below them just as constructed blocks do in Minecraft.
        // Unlike ground-burrowing squash bees they do not need bare soil.
        if (!groundNesting) {
            BlockPos footing = pos.below();
            return level.getBlockState(footing).isFaceSturdy(level, footing, Direction.UP);
        }
        BlockState below = level.getBlockState(pos.below());
        // Ground-nesting squash bees need accessible bare soil. Turf, podzol
        // and mycelium are not substitutes for an exposed nesting surface.
        return below.is(Blocks.DIRT) || below.is(Blocks.COARSE_DIRT)
                || below.is(Blocks.SAND) || below.is(Blocks.RED_SAND);
    }

    @Override
    protected BlockState updateShape(BlockState state, Direction direction, BlockState neighborState,
                                     LevelAccessor level, BlockPos pos, BlockPos neighborPos) {
        // Avoid a floating burrow after its exposed soil is removed or covered.
        if (direction == Direction.DOWN && !canSurvive(state, level, pos)) {
            return Blocks.AIR.defaultBlockState();
        }
        return super.updateShape(state, direction, neighborState, level, pos, neighborPos);
    }

    @Override
    public void randomTick(BlockState state, ServerLevel level, BlockPos pos, RandomSource random) {
        // The activity gauge represents a recent habitat observation, not permanent occupancy.
        // One in four random ticks checks nearby bees; absent bees slowly reduce the gauge.
        // USDA ARS reports squash bees forage especially early in the morning.
        // The activity gauge is a recent observation: pausing outside this window
        // avoids treating the species' normal afternoon/night inactivity as failure.
        // Day ticks 0..5999 span dawn to before midday in the Minecraft day cycle.
        if (beeSpecies.equals("squash_bee") && level.getDayTime() % 24000L >= 6000L) {
            return;
        }
        if (random.nextInt(4) != 0) return;
        int activity = state.getValue(ACTIVITY);
        int nearbyBees = countMatchingBees(level, pos);
        boolean active = nearbyBees > 0 && hasForage(level, pos);
        if (active && activity < 3) {
            level.setBlock(pos, state.setValue(ACTIVITY, activity + 1), 3);
        } else if (!active && activity > 0 && random.nextInt(3) == 0) {
            level.setBlock(pos, state.setValue(ACTIVITY, activity - 1), 3);
        }

        // Established and flower-supported nesting sites can nurture a limited
        // new cohort. This is bounded Minecraft emergence, NOT colony storage,
        // honey production, or a real larval timer.
        if (active && activity == 3 && nearbyBees < populationLimit()
                && random.nextInt(32) == 0 && level.getBlockState(pos.above()).isAir()) {
            Entity next = BuiltInRegistries.ENTITY_TYPE.get(
                    ResourceLocation.fromNamespaceAndPath("gugugaga", beeSpecies)).create(level);
            if (next instanceof Bee child) {
                child.setPos(pos.getX() + 0.5D, pos.getY() + 1.0D, pos.getZ() + 0.5D);
                child.setBaby(true);
                // A nest-origin marker is retained for later bee-AI extensions.
                child.getPersistentData().putLong("gugugaga_wild_nest_origin", pos.asLong());
                level.addFreshEntity(child);
            }
        }
    }

    private int populationLimit() {
        // Bumblebees are social and may maintain a small local group. The
        // cavity/ground solitary species are capped to a lower nearby count.
        return beeSpecies.equals("bumblebee") ? 4 : 2;
    }

    private int countMatchingBees(ServerLevel level, BlockPos pos) {
        EntityType<?> expectedType = BuiltInRegistries.ENTITY_TYPE.get(
                ResourceLocation.fromNamespaceAndPath("gugugaga", beeSpecies));
        AABB searchArea = new AABB(pos).inflate(8.0D);
        int count = 0;
        // Filter to this habitat's species during the entity query so unrelated
        // vanilla bees do not allocate list entries or require registry-key lookups.
        for (Bee bee : level.getEntitiesOfClass(Bee.class, searchArea,
                candidate -> candidate.isAlive() && candidate.getType() == expectedType)) {
            count++;
        }
        return count;
    }

    private boolean hasForage(ServerLevel level, BlockPos pos) {
        BlockPos.MutableBlockPos candidate = new BlockPos.MutableBlockPos();
        // Search the same 9x9x4 volume from the nearest columns outward. Check
        // chunk availability once per x/z column; never force-load adjacent terrain.
        for (int ring = 0; ring <= 4; ring++) {
            for (int dx = -ring; dx <= ring; dx++) {
                for (int dz = -ring; dz <= ring; dz++) {
                    if (ring != 0 && dx != -ring && dx != ring
                            && dz != -ring && dz != ring) {
                        continue;
                    }
                    int x = pos.getX() + dx;
                    int z = pos.getZ() + dz;
                    candidate.set(x, pos.getY(), z);
                    if (!level.hasChunkAt(candidate)) {
                        continue;
                    }
                    for (int dy = -1; dy <= 2; dy++) {
                        candidate.set(x, pos.getY() + dy, z);
                        BlockState nearby = level.getBlockState(candidate);
                        if (!beeSpecies.equals("squash_bee") && nearby.is(BlockTags.FLOWERS)) {
                            return true;
                        }
                        if (nearby.getBlock() instanceof AgricultureCropBlock crop
                                && nearby.getValue(AgricultureCropBlock.AGE) >= 4) {
                            String id = BuiltInRegistries.BLOCK.getKey(crop).getPath();
                            if (beeSpecies.equals("squash_bee")) {
                                // Cucurbita specialist: zucchini and pumpkin only.
                                if (SQUASH_FORAGE_CROPS.contains(id)) return true;
                            } else if (beeSpecies.equals("bumblebee")
                                    && BUMBLEBEE_SOLANACEOUS_CROPS.contains(id)) {
                                // Bumblebees can buzz-pollinate tomato and eggplant flowers.
                                return true;
                            } else if (GENERAL_FORAGE_CROPS.contains(id)) {
                                return true;
                            }
                        }
                    }
                }
            }
        }
        return false;
    }

    @Override
    public InteractionResult useWithoutItem(BlockState state, Level level, BlockPos pos,
                                            Player player, BlockHitResult hit) {
        if (level.isClientSide) return InteractionResult.SUCCESS;
        int population = level instanceof ServerLevel server ? countMatchingBees(server, pos) : 0;
        player.displayClientMessage(Component.translatable(
                "message.gugugaga.bee_habitat_activity",
                state.getValue(ACTIVITY), 3, population, populationLimit()), true);
        return InteractionResult.CONSUME;
    }
}
